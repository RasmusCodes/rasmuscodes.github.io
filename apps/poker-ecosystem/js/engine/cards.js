export function gameOf(code) {
  const g = GAMES[String(code).toUpperCase()];
  if (!g) throw new Error(`unknown game '${code}'`);
  return g;
}

/** Cards of a game's deck in the Rust iteration order (suit-major: clubs 2..A, diamonds, ...). */
export function deckCards(game) {
  const short = game.rules !== 'standard';
  const out = [];
  for (let s = 0; s < 4; s++) for (let r = short ? 4 : 0; r < 13; r++) out.push(r * 4 + s);
  return out;
}

// ---------------------------------------------------------------- combos and classes

export const NUM_COMBOS = 1326;
export function comboIndex(a, b) { const hi = Math.max(a, b), lo = Math.min(a, b); return (hi * (hi - 1)) / 2 + lo; }
const COMBO_CARDS = (() => {
  const t = [];
  for (let hi = 1; hi < 52; hi++) for (let lo = 0; lo < hi; lo++) t[comboIndex(hi, lo)] = [hi, lo];
  return t;
})();
export const comboCards = (i) => COMBO_CARDS[i];

/** Grid index (row * 13 + col), rows/cols from ace (0) to deuce (12); suited above the diagonal. */
export function classOf(a, b) {
  const [hi, lo] = rankOf(a) >= rankOf(b) ? [a, b] : [b, a];
  const rh = 12 - rankOf(hi), rl = 12 - rankOf(lo);
  if (rankOf(hi) === rankOf(lo)) return rh * 13 + rh;
  return suitOf(hi) === suitOf(lo) ? rh * 13 + rl : rl * 13 + rh;
}
export function className(cls) {
  const row = Math.floor(cls / 13), col = cls % 13, rc = (i) => RANKS[12 - i];
  if (row === col) return rc(row) + rc(col);
  return row < col ? rc(row) + rc(col) + 's' : rc(col) + rc(row) + 'o';
}
export function classSize(cls) { const row = Math.floor(cls / 13), col = cls % 13; return row === col ? 6 : row < col ? 4 : 12; }
const CLASS_COMBOS = (() => {
  const t = Array.from({ length: 169 }, () => []);
  for (let i = 0; i < NUM_COMBOS; i++) { const [a, b] = COMBO_CARDS[i]; t[classOf(a, b)].push(i); }
  return t;
})();
export const classCombos = (cls) => CLASS_COMBOS[cls];

