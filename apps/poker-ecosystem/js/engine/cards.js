// ---------------------------------------------------------------- hold'em ranges

function parseRank(ch) { const i = RANKS.indexOf(ch.toUpperCase()); return i < 0 ? null : i; }
function classIndex(hi, lo, suited) {
  const rh = 12 - hi, rl = 12 - lo;
  if (hi === lo) return rh * 13 + rh;
  return suited ? rh * 13 + rl : rl * 13 + rh;
}
function parseClass(s) {
  if (s.length < 2 || s.length > 3) throw new Error(`bad hand class '${s}'`);
  const a = parseRank(s[0]), b = parseRank(s[1]);
  if (a === null || b === null) throw new Error(`bad rank in '${s}'`);
  const [hi, lo] = a >= b ? [a, b] : [b, a];
  let suited = null;
  if (s.length === 3) {
    const x = s[2].toLowerCase();
    if (x === 's') suited = true; else if (x === 'o') suited = false; else throw new Error(`bad suffix in '${s}'`);
  }
  if (hi === lo && suited === true) throw new Error(`a pair cannot be suited: '${s}'`);
  return [hi, lo, suited];
}
function specCombos([hi, lo, suited]) {
  if (hi === lo) return CLASS_COMBOS[classIndex(hi, lo, false)].slice();
  const v = [];
  if (suited !== false) v.push(...CLASS_COMBOS[classIndex(hi, lo, true)]);
  if (suited !== true) v.push(...CLASS_COMBOS[classIndex(hi, lo, false)]);
  return v;
}
function parseWeight(w) {
  const t = w.trim();
  const v = t.endsWith('%') ? parseFloat(t) / 100 : parseFloat(t);
  if (!Number.isFinite(v) || v < 0 || v > 1) throw new Error(`bad weight '${w}'`);
  return v;
}
export function topPercent(pct, ranking = preflopRanking()) {
  const w = new Float64Array(NUM_COMBOS);
  let remaining = (Math.min(Math.max(pct, 0), 100) / 100) * NUM_COMBOS;
  for (const cls of ranking) {
    if (remaining <= 1e-9) break;
    const size = classSize(cls), x = Math.min(remaining / size, 1);
    for (const c of CLASS_COMBOS[cls]) w[c] = x;
    remaining -= x * size;
  }
  return w;
}
function itemCombos(item) {
  const lower = item.toLowerCase();
  if (lower === 'random' || lower === 'any' || lower === 'all') return Array.from({ length: NUM_COMBOS }, (_, i) => i);
  if (item.endsWith('%')) {
    const w = topPercent(parseFloat(item));
    const out = [];
    for (let i = 0; i < NUM_COMBOS; i++) if (w[i] >= 0.5) out.push(i);
    return out;
  }
  if (item.length === 4 && 'cdhsCDHS'.includes(item[1]) && 'cdhsCDHS'.includes(item[3])) {
    const a = parseCard(item.slice(0, 2)), b = parseCard(item.slice(2, 4));
    if (a === b) throw new Error(`duplicate card in '${item}'`);
    return [comboIndex(a, b)];
  }
  const dash = item.indexOf('-');
  if (dash > 0) {
    const f = parseClass(item.slice(0, dash).trim()), t = parseClass(item.slice(dash + 1).trim());
    const out = [];
    if (f[0] === f[1] && t[0] === t[1]) {
      for (let r = Math.min(f[0], t[0]); r <= Math.max(f[0], t[0]); r++) out.push(...specCombos([r, r, null]));
      return out;
    }
    if (f[0] !== t[0] || f[2] !== t[2] || f[0] === f[1]) throw new Error(`span '${item}' must keep the top card and suitedness`);
    for (let k = Math.min(f[1], t[1]); k <= Math.max(f[1], t[1]); k++) out.push(...specCombos([f[0], k, f[2]]));
    return out;
  }
  if (item.endsWith('+')) {
    const [hi, lo, suited] = parseClass(item.slice(0, -1));
    const out = [];
    if (hi === lo) for (let r = hi; r <= 12; r++) out.push(...specCombos([r, r, null]));
    else for (let k = lo; k < hi; k++) out.push(...specCombos([hi, k, suited]));
    return out;
  }
  return specCombos(parseClass(item));
}
/** Weights for the 1,326 combos from range notation (later items override earlier ones). */
export function parseHoldemRange(s) {
  const w = new Float64Array(NUM_COMBOS);
  for (const raw of String(s).split(/[,\s]+/)) {
    const tok = raw.trim();
    if (!tok) continue;
    const colon = tok.indexOf(':');
    const item = colon >= 0 ? tok.slice(0, colon) : tok;
    const weight = colon >= 0 ? parseWeight(tok.slice(colon + 1)) : 1;
    for (const c of itemCombos(item)) w[c] = weight;
  }
  return w;
}

// ---------------------------------------------------------------- Omaha patterns

function* subsets(arr, k, start = 0, prefix = []) {
  if (prefix.length === k) { yield prefix; return; }
  for (let i = start; i <= arr.length - (k - prefix.length); i++) yield* subsets(arr, k, i + 1, [...prefix, arr[i]]);
}
function suitShape(hand) {
  const c = [0, 0, 0, 0];
  for (const x of hand) c[suitOf(x)]++;
  return c.filter((v) => v > 0).sort((a, b) => b - a).join('');
}
function parsePattern(item, n) {
  let low = item.toLowerCase(), shape = 'any';
  if (low.endsWith('ds')) { shape = 'ds'; low = low.slice(0, -2); }
  else if (low.endsWith('ss')) { shape = 'ss'; low = low.slice(0, -2); }
  else if (low.endsWith('3s')) { shape = '3s'; low = low.slice(0, -2); }
  else if (low.length === n + 1 && low.endsWith('r')) { shape = 'r'; low = low.slice(0, -1); }
  else if (low.length === n + 1 && low.endsWith('m')) { shape = 'm'; low = low.slice(0, -1); }
  if (low.length !== n) throw new Error(`pattern '${item}' must have ${n} rank symbols`);
  const ranks = [];
  for (const ch of low) {
    if (ch === 'x' || ch === '*') continue;
    const r = parseRank(ch);
    if (r === null) throw new Error(`bad rank '${ch}' in '${item}'`);
    ranks.push(r);
  }
  return { ranks, shape };
}
function matchPattern(p, hand) {
  const counts = new Array(13).fill(0);
  for (const c of hand) counts[rankOf(c)]++;
  for (const r of p.ranks) { if (!counts[r]) return false; counts[r]--; }
  const sh = suitShape(hand), n = hand.length;
  switch (p.shape) {
    case 'ds': return n === 4 ? sh === '22' : sh === '221';
    case 'ss': return n === 4 ? sh === '211' : sh === '2111';
    case 'r': return sh.split('').every((x) => x === '1');
    case '3s': return sh[0] === '3';
    case 'm': return Number(sh[0]) === n;
    default: return true;
  }
}
/** Omaha range (same pattern language as the Rust engine) as { hands, weights }. */
export function parseOmahaRange(s, n, game, deadSet) {
  const avail = deckCards(game).filter((c) => !deadSet.has(c));
  const chosen = new Map();
  const order = [];
  const add = (h, w) => { const k = h.join(','); if (!chosen.has(k)) order.push(h); chosen.set(k, w); };
  for (const raw of String(s).split(/[,\s]+/)) {
    const tok = raw.trim();
    if (!tok) continue;
    const colon = tok.indexOf(':');
    const item = colon >= 0 ? tok.slice(0, colon) : tok;
    const w = colon >= 0 ? parseWeight(tok.slice(colon + 1)) : 1;
    if (item.toLowerCase() === 'random' || item.toLowerCase() === 'any') { for (const h of subsets(avail, n)) add(h.slice(), w); continue; }
    if (item.length === 2 * n) {
      try {
        const cards = parseCards(item);
        if (cards.length === n) {
          if (cards.some((c) => deadSet.has(c) || !avail.includes(c))) continue;
          add(cards.slice().sort((a, b) => a - b), w);
          continue;
        }
      } catch (e) { /* not a specific hand: a pattern */ }
    }
    const p = parsePattern(item, n);
    for (const h of subsets(avail, n)) if (matchPattern(p, h)) add(h.slice(), w);
  }
  const hands = [], weights = [];
  for (const h of order) { const w = chosen.get(h.join(',')); if (w > 0) { hands.push(h); weights.push(w); } }
  return { hands, weights: Float64Array.from(weights) };
}

/** A range for any game as { hands, weights }, in the Rust engine's order. */
export function parseHandList(game, s, deadSet = new Set()) {
  if (game.hole === 2) {
    const w = parseHoldemRange(s);
    const deck = new Set(deckCards(game));
    const hands = [], weights = [];
    for (let i = 0; i < NUM_COMBOS; i++) {
      if (w[i] <= 0) continue;
      const [a, b] = COMBO_CARDS[i];
      if (deadSet.has(a) || deadSet.has(b) || !deck.has(a) || !deck.has(b)) continue;
      hands.push([b, a]);
      weights.push(w[i]);
    }
    return { hands, weights: Float64Array.from(weights) };
  }
  return parseOmahaRange(s, game.hole, game, deadSet);
}

// ---------------------------------------------------------------- RNG (xoshiro128**, seeded)

export function rng(seed) {
  let a = seed >>> 0 || 1, b = 0x9e3779b9, c = 0x243f6a88, d = 0xb7e15162;
  const next = () => {
    const r = Math.imul(Math.imul(b, 5) << 7 | Math.imul(b, 5) >>> 25, 9) >>> 0;
    const t = b << 9;
    c ^= a; d ^= b; b ^= c; a ^= d; c ^= t; d = d << 11 | d >>> 21;
    return r;
  };
  for (let i = 0; i < 8; i++) next();
  return {
    u32: next,
    float: () => next() / 4294967296,
    below: (n) => Math.floor((next() / 4294967296) * n),
  };
}
