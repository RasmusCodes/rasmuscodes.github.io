// Cards, combos, hand classes, ranges and a seeded RNG.
// A port of crates/pe-cards: card id = rank * 4 + suit (rank 0..12 = 2..A,
// suit 0..3 = c d h s). Card sets are plain arrays of ids; collision checks use
// two 32-bit words (ids 0-31 and 32-51).

export const RANKS = '23456789TJQKA';
export const SUITS = 'cdhs';
export const rankOf = (c) => c >> 2;
export const suitOf = (c) => c & 3;
export const cardStr = (c) => RANKS[c >> 2] + SUITS[c & 3];
export const cardsStr = (cs) => cs.map(cardStr).join('');

export function parseCard(s) {
  const t = s.trim();
  const m = /^(10|[2-9TJQKAtjqka])([cdhsCDHS])$/.exec(t);
  if (!m) throw new Error(`bad card '${s}'`);
  const r = m[1] === '10' ? 8 : RANKS.indexOf(m[1].toUpperCase());
  return r * 4 + SUITS.indexOf(m[2].toLowerCase());
}

export function parseCards(str) {
  const clean = (str || '').replace(/[\[\],\s-]/g, '');
  const out = [];
  for (let i = 0; i < clean.length;) {
    if (clean[i] === '1' && clean[i + 1] === '0') { out.push(parseCard('T' + clean[i + 2])); i += 3; continue; }
    if (i + 1 >= clean.length) throw new Error(`dangling '${clean[i]}' in '${str}'`);
    out.push(parseCard(clean.slice(i, i + 2)));
    i += 2;
  }
  if (new Set(out).size !== out.length) throw new Error(`duplicate card in '${str}'`);
  return out;
}

// two-word masks for collision checks
export function maskLo(cards) { let m = 0; for (const c of cards) if (c < 32) m |= 1 << c; return m; }
export function maskHi(cards) { let m = 0; for (const c of cards) if (c >= 32) m |= 1 << (c - 32); return m; }

/** Bit position of a card in the Rust suit-major layout (suit * 16 + rank). */
export const suitMajorBit = (c) => (c & 3) * 16 + (c >> 2);

